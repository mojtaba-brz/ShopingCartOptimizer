const assert=require('node:assert/strict'),c=require('../../cartoptimizer/web/comparison.js');
const p=(title,price,extra={})=>({title,regular_price:price,promo_price:null,...extra});
const item={id:'rice',name:'برنج ۱ کیلوگرم',quantity:1};
let rows=[p('برنج ۱ کیلوگرم',1000000),p('برنج ۲ کیلوگرم',1600000)];
let plan=c.plan(item,rows);assert.equal(plan.product.title,'برنج ۲ کیلوگرم');assert.equal(plan.cost,1600000);assert.equal(plan.unit_price,800000);assert.equal(plan.quantity,1);
assert.deepEqual(c.options(item,rows).map(p=>p.unit_price),[800000,1000000]);
assert.equal(c.measure('تخم مرغ بسته ۶ عددی').value,6);assert.equal(c.measure('ماست بسته ۶ عددی 200 گرم').unit,'unknown');
assert.deepEqual(c.measure('نوشیدنی ۶×۲۰۰ میلی لیتر'),{unit:'ml',value:1200});
assert.equal(c.plan({id:'e',name:'تخم مرغ',quantity:5},[p('تخم مرغ ۶ عددی',120000)]).quantity,1);
assert.equal(c.unitPrice(p('برنج ۵۰۰ گرم',1000000,{promo_price:600000})),1200000);
assert.equal(c.unitPrice(p('برنج ۵۰۰ گرم',1000000,{promo_price:600000}),true),2000000);
assert.equal(c.unitPrice(p('برنج ۵۰۰ گرم',1000000,{regular_verified:false}),true),null);
rows=[p('برنج ۱ کیلوگرم',1000000,{store_name:'الف',store_id:'a'}),p('برنج ۱ کیلوگرم',1000000,{store_name:'ب',store_id:'b'})];assert.equal(c.options(item,rows).length,2);
assert.notEqual(c.options(item,rows)[0].key,c.options(item,rows)[1].key);
assert.equal(c.plan(item,[p('برنج ۱ لیتر',10000)]),null);
assert.equal(c.plan(item,[p('برنج ۶ عددی 200 گرم',10000)]),null);
assert.equal(c.plan(item,[p('برنج ۱ کیلوگرم',1000000)],'',false,2).cost,2000000);
rows=Array.from({length:20},(_,i)=>p('برنج '+(i+1)+' کیلوگرم',2000000+i*10000));assert.equal(c.options({name:'برنج',quantity:1},rows)[0].title,'برنج 20 کیلوگرم');
assert.equal(c.plan({...item,name:'برنج ۱۰۰ کیلوگرم'},[p('برنج ۱ کیلوگرم',100),p('برنج ۱۰ کیلوگرم',10000)]).quantity,10);
console.log('Normalized kg/litre/item ordering, larger-package preference, merchant identity and size guards passed');
